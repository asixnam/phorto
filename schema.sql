CREATE POLICY "Allow public insert access for resume" ON public.resume FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update access for resume" ON public.resume FOR UPDATE USING (true);
CREATE POLICY "Allow public delete access for resume" ON public.resume FOR DELETE USING (true);

-- About Me Policies
